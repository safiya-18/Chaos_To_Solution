import React from 'react';
import { ChallengeCard } from './ChallengeCard.jsx';
import { ResourceLink } from './ResourceLink.jsx';
import { Sparkles, Archive, Hash, Clock, CheckCircle } from 'lucide-react';

export function ChallengeResults({ challengeData }) {
  if (!challengeData) return null;

  const { id, theme, source, generatedAt, challenge } = challengeData;
  const { problem, restriction, resource, deliverable } = challenge;

  const isAiSource = source === 'ai';

  // Format generated time if present
  let formattedTime = '';
  try {
    if (generatedAt) {
      formattedTime = new Date(generatedAt).toLocaleTimeString([], {
        hour: '2-digit',
        minute: '2-digit'
      });
    }
  } catch {
    formattedTime = '';
  }

  return (
    <section
      id="challenge-results-section"
      className="w-full mt-10 scroll-mt-6"
      aria-labelledby="challenge-mission-heading"
    >
      {/* Top Header Bar */}
      <div className="p-4 sm:p-5 rounded-2xl bg-white border-2 border-[#11151C] mb-5 flex flex-wrap items-center justify-between gap-3 shadow-sm">
        <div className="flex flex-wrap items-center gap-2.5">
          <span className="text-xs font-black uppercase tracking-wider px-3 py-1 rounded-full bg-[#11151C] text-white">
            {theme}
          </span>

          {id && (
            <span className="flex items-center gap-1 text-xs font-mono text-[#4A453E] px-2.5 py-1 rounded-full bg-[#F7F3EA] border border-[#11151C]/25 font-bold">
              <Hash className="w-3 h-3 text-[#111820]" />
              <span>{id}</span>
            </span>
          )}

          {formattedTime && (
            <span className="flex items-center gap-1 text-xs text-[#524B43] px-2.5 py-1 rounded-full bg-[#F7F3EA] border border-[#11151C]/25 font-medium">
              <Clock className="w-3 h-3 text-[#111820]" />
              <span>{formattedTime}</span>
            </span>
          )}
        </div>

        {/* Source indicator */}
        <div className="flex items-center gap-2">
          {isAiSource ? (
            <span
              id="source-indicator-badge"
              className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-extrabold bg-[#CDE7FB] text-[#111820] border-2 border-[#11151C] shadow-xs"
              title="Generated by AI challenge synthesis"
            >
              <Sparkles className="w-3.5 h-3.5 text-[#304DB4]" aria-hidden="true" />
              <span>AI Generated</span>
            </span>
          ) : (
            <span
              id="source-indicator-badge"
              className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-extrabold bg-[#FEF3C7] text-[#111820] border-2 border-[#11151C] shadow-xs"
              title="Verified fallback from curated challenge bank"
            >
              <Archive className="w-3.5 h-3.5 text-[#F59E0B]" aria-hidden="true" />
              <span>Backup Challenge</span>
            </span>
          )}
        </div>
      </div>

      {/* The 4 Challenge Cards Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        {/* 01 — Problem Statement */}
        <ChallengeCard
          number="01"
          label="Problem Statement"
          title={problem.title}
        >
          <p>{problem.statement}</p>
        </ChallengeCard>

        {/* 02 — Restriction */}
        <ChallengeCard
          number="02"
          label="Technical Restriction"
          title={restriction.name}
        >
          <div className="p-3.5 rounded-xl bg-[#FEF3C7] border border-[#11151C]/20 text-[#111820] font-mono text-xs leading-relaxed">
            <span className="font-extrabold uppercase tracking-wide block mb-1 text-[#92400E]">
              Constraint Rule:
            </span>
            {restriction.rule}
          </div>
        </ChallengeCard>

        {/* 03 — Resource */}
        <ChallengeCard
          number="03"
          label="Prescribed Resource"
          title={resource.name}
          subtitle={resource.type}
        >
          <p className="mb-2">{resource.guidance}</p>
          <ResourceLink
            docsUrl={resource.docsUrl}
            name={resource.name}
          />
        </ChallengeCard>

        {/* 04 — Expected Deliverable */}
        <ChallengeCard
          number="04"
          label="Expected Deliverable"
          title="Functional Prototype"
        >
          <div className="p-3.5 rounded-xl bg-[#DCFCE7] border border-[#11151C]/20 text-[#111820] text-xs sm:text-sm leading-relaxed flex items-start gap-2.5">
            <CheckCircle className="w-4 h-4 text-[#16A34A] shrink-0 mt-0.5" aria-hidden="true" />
            <span className="font-medium whitespace-pre-line">{deliverable}</span>
          </div>
          <p className="mt-3 text-xs text-[#6B6358]">
            Demonstrate this working feature live to the judges at the end of the 3-hour sprint.
          </p>
        </ChallengeCard>
      </div>
    </section>
  );
}
